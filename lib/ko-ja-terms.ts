/** 검색어 통째일 때만 쓰는 말 — 다른 말 속에 끼거나(기타 굿즈·메이플스토리) 다른 뜻이 있는 말(강백호). 조각 치환에서 뺀다 */
export const KO_JA_QUERY_ONLY: ReadonlySet<string> = new Set([
  "기타", "리바이", "커비", "드퀘", "플스", "벤투스", "키스미", "미뇽", "강백호", "이사기",
  "스니커즈", "운동화", "아크스타", "만화책", // 2026-11-04: 스니커즈 초콜릿·운동화 끈처럼 다른 말에 끼는 말
]);

export type KoJaPiece = { ja: string } | { ko: string };
const HANGUL = /[가-힣ㄱ-ㅎㅏ-ㅣ]/;
const NOUNS = Object.keys(KO_JA_TERMS).filter((k) => !KO_JA_QUERY_ONLY.has(k)).sort((a, b) => b.length - a.length);

/** 표에 있으면 큐레이션된 일본어, 없으면 null. 공백·대소문자 정규화 후 통째 비교 */
export function curatedJa(ko: string): string | null {
  const k = ko.trim().replace(/\s+/g, " ").toLowerCase();
  for (const [key, ja] of Object.entries(KO_JA_TERMS)) if (key.toLowerCase() === k) return ja;
  return null;
}

/**
 * 검색어를 사전 말(ja 확정)과 번역할 구간(ko)으로 자른다. 사전 말이 없으면 null(통째 번역).
 * 긴 말부터, 다른 말에 붙어 있어도(치이카와인형) 치환한다. 한글이 없는 구간(A상의 A, 숫자, 영문)은 ja 로 그대로 둔다.
 * 예: 「치이카와 미개봉 A상」을 통째 번역하면 千川未開封A賞 → 0건.
 */
export function splitKoJaQuery(q: string): KoJaPiece[] | null {
  const text = q.trim().replace(/\s+/g, " ");
  const out: KoJaPiece[] = [];
  let buf = "";
  let hit = false;
  const flush = () => {
    for (const part of buf.trim() ? [buf.trim()] : []) out.push(HANGUL.test(part) ? { ko: part } : { ja: part });
    buf = "";
  };
  for (let i = 0; i < text.length; ) {
    const noun = NOUNS.find((k) => text.startsWith(k, i));
    if (noun) { flush(); out.push({ ja: KO_JA_TERMS[noun] }); i += noun.length; hit = true; continue; }
    buf += text[i++]; // 사전 밖 낱말은 이어서 한 번에 번역(문맥 유지)
  }
  flush();
  return hit ? out : null;
}
